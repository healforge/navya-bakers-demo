export function translate(language: Language, message: string, values?: Record<string, string | number>): string {
  const localized = language === 'ml' && Object.hasOwn(malayalam, message) ? malayalam[message] : message
  if (!values) return localized
  return localized.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  )
}
